// Clawd painter: turns a "clawd" scene into a hand-painted clip with the Claude Animation Base kit
// (vendor/skills/clawd, MIT, p5.brush). The kit is copied to vendor/clawd-studio once (square 1080×1080 canvas instead of
// 1920×1080, our generated shot instead of the demo), then its own renderer paints the shot with Playwright's Chromium.
// Clips land in <work>/art/<key>/clip.mp4, where key = the scene's look (not its words or length), see artKey().
const fs = require("fs"), path = require("path"), crypto = require("crypto");
const U = require("./util"), S = require("./skills");

const STUDIO = path.join(U.ROOT, "vendor", "clawd-studio"), FPS = 24, SIZE = 1080;

// What a clawd/broll scene looks like, without its words and length: the same picture keeps the same clip.
function artKey(scene) {
  const { say, dur, _art, ...look } = scene;
  return crypto.createHash("sha1").update(JSON.stringify(look)).digest("hex").slice(0, 12);
}

// Copy the pulled kit into the studio (again when the kit was updated) and install its packages.
async function ensureStudio(log = () => {}) {
  const src = S.vendorDir("clawd");
  if (!fs.existsSync(path.join(src, "src", "clawd.js"))) throw new Error("Claude Animation Base isn't pulled yet: Settings → Skills → Pull.");
  const commit = (require("child_process").execFileSync("git", ["-C", src, "rev-parse", "HEAD"], { windowsHide: true }).toString().trim());
  const stamp = path.join(STUDIO, ".from");
  if (!fs.existsSync(stamp) || fs.readFileSync(stamp, "utf8") !== commit) {
    log("setting up the Clawd studio (a square copy of the kit)…");
    for (const f of ["src", "render.mjs", "studio.html", "package.json", "package-lock.json"]) {
      fs.rmSync(path.join(STUDIO, f), { recursive: true, force: true });
      fs.cpSync(path.join(src, f), path.join(STUDIO, f), { recursive: true });
    }
    const patch = (f, a, b) => { const p = path.join(STUDIO, f), s = fs.readFileSync(p, "utf8"); if (!s.includes(a)) throw new Error(`Clawd kit changed: can't find "${a}" in ${f}`); fs.writeFileSync(p, s.replace(a, b)); };
    patch("src/core.js", "const W = 1920, H = 1080;", `const W = ${SIZE}, H = ${SIZE};`);
    patch("studio.html", '<canvas id="out" width="1920" height="1080">', `<canvas id="out" width="${SIZE}" height="${SIZE}">`);
    patch("studio.html", '<script src="src/scenes/demo.js"></script>', '<script src="src/scenes/reel.js"></script>');
    patch("render.mjs", "--window-size=1920,1080", `--window-size=${SIZE},${SIZE}`);
    fs.writeFileSync(stamp, commit);
  }
  if (!fs.existsSync(path.join(STUDIO, "node_modules", "p5.brush"))) {
    log("installing the Clawd kit's packages (p5, p5.brush, puppeteer-core)…");
    await U.run(process.platform === "win32" ? "npm.cmd" : "npm", ["install", "--no-audit", "--no-fund"], { cwd: STUDIO, log, shell: true });
  }
}

// The shot for one scene: Clawd in a setting, acting `action`, changing from one emotion to another (the event).
function shotJs(sc, dur) {
  const j = JSON.stringify;
  return `// Generated by Reel Factory (lib/clawd.js) for one "clawd" scene. Square ${SIZE}×${SIZE}.
(() => {
  const SC = ${j({ action: sc.action, from: sc.from, to: sc.to, prop: sc.prop || null, hat: sc.hat || null, setting: sc.setting || "paper" })};
  const DUR = ${dur.toFixed(2)}, SWITCH = DUR * 0.45, X = ${SIZE / 2}, Y = ${Math.round(SIZE * 0.8)}, UNIT = 40;

  function backdrop(t) {
    boilSeed('bg');
    if (SC.setting === 'night') {
      paint(rectPts(-200, -200, W + 400, H + 400), { wash: PAL.night, ink: null });
      paint(ellPts(W * .5, H * .25, W * .6, H * .3, 26, 10), { fill: PAL.indigo, fillOp: 110, bleed: .3, ink: null });
      for (let i = 0; i < 26; i++) { boilSeed('st' + i); const tw = .6 + .4 * Math.sin(t * (2 + 2 * hash(i + 3)) + i);
        paint(starPts(hash(i) * W, hash(i + 50) * H * .55, (3 + 4 * hash(i + 9)) * tw, .35, 4), { wash: PAL.cream, ink: null }); }
      boilSeed('moon'); paint(ellPts(W * .8, H * .18, 55, 55, 22, 1.5), { wash: PAL.cream, fill: PAL.ochre, fillOp: 40, ink: PAL.ink, sw: .8 });
      boilSeed('ground'); paint(ellPts(W * .5, H * 1.05, W * .8, H * .3, 36, 2), { wash: mixCol(PAL.sap, PAL.night, .45), ink: PAL.ink, sw: 1 });
    } else if (SC.setting === 'meadow') {
      paint(rectPts(-200, -200, W + 400, H + 400), { wash: PAL.sky, ink: null });
      boilSeed('sun'); glow(W * .78, H * .2, 160, '#FFE08A', .6); paint(ellPts(W * .78, H * .2, 60, 60, 22, 1.5), { wash: '#FFE27A', ink: PAL.ink, sw: .8 });
      boilSeed('hill'); paint(ellPts(W * .5, H * 1.02, W * .85, H * .34, 40, 2), { wash: PAL.sap, fill: mixCol(PAL.sap, PAL.ink, .2), fillOp: 80, ink: PAL.ink, sw: 1 });
    } else if (SC.setting === 'desk') {
      boilSeed('wall'); paint(rectPts(-100, -100, W + 200, H * .7 + 100), { fill: PAL.cream, fillOp: 140, bleed: .2, ink: null });
      boilSeed('desk'); paint(rectPts(W * .06, H * .8, W * .88, H * .06, 2), { wash: PAL.clayDk, fill: mixCol(PAL.clayDk, PAL.ink, .3), fillOp: 80, ink: PAL.ink, sw: 1 });
      boilSeed('lamp'); inkLine([[W * .15, H * .8], [W * .15, H * .5], [W * .25, H * .42]], 1, PAL.ink, 'ink', .3);
      paint(ellPts(W * .27, H * .44, 40, 22, 16, 1), { wash: PAL.ochre, ink: PAL.ink, sw: .8 }); glow(W * .27, H * .48, 140, '#FFD96A', .35);
    } else {
      boilSeed('blob'); paint(ellPts(W * .5, H * .55, W * .42, H * .38, 30, 14), { fill: PAL.clayLt, fillOp: 60, bleed: .3, ink: null });
    }
    boilSeed('shadow'); paint(ellPts(X, Y + 6, UNIT * 6, UNIT * 1.1, 20, 1), { fill: PAL.ink, fillOp: 35, ink: null });
  }

  // a held prop, drawn at the right arm's tip (arm space: +x runs out along the arm)
  function prop(u, sw) {
    const k = SC.prop;
    if (k === 'laptop') { paint(rectPts(-u * 1.2, -u * 1.6, u * 2.8, u * 1.8, .4), { wash: '#8E97A8', ink: PAL.ink, sw }); paint(rectPts(-u * .9, -u * 1.3, u * 2.2, u * 1.2, .2), { wash: PAL.sky, ink: null }); }
    if (k === 'box') paint(rectPts(-u * .4, -u * 1.8, u * 2.4, u * 2, .4), { wash: PAL.ochre, ink: PAL.ink, sw });
    if (k === 'book') paint(rectPts(-u * .2, -u * 1.5, u * 1.6, u * 2, .3), { wash: PAL.violet, ink: PAL.ink, sw });
    if (k === 'coffee') { paint(rectPts(0, -u * 1.4, u * 1.2, u * 1.5, .3), { wash: PAL.cream, ink: PAL.ink, sw }); paint(ellPts(u * .6, -u * 1.35, u * .55, u * .18, 12), { wash: '#6B4423', ink: null }); }
    if (k === 'rocket') { paint(ellPts(u * .8, -u * 1.2, u * .5, u * 1.3, 16, .3), { wash: PAL.cream, ink: PAL.ink, sw }); paint(ellPts(u * .8, -u * 1.6, u * .2, u * .2, 10), { wash: PAL.sky, ink: PAL.ink, sw: sw * .6 }); }
    if (k === 'star') { glow(u * .8, -u * .8, u * 3, '#FFD96A', .5); paint(starPts(u * .8, -u * .8, u * 1.2, .5, 5), { wash: '#FFE27A', ink: PAL.ink, sw }); }
    if (k === 'bug') { paint(ellPts(u * .8, -u * .9, u * .7, u * .5, 14, .3), { wash: '#4A7A3A', ink: PAL.ink, sw }); for (const s of [-1, 0, 1]) inkLine([[u * (.8 + s * .4), -u * .5], [u * (.8 + s * .6), -u * .1]], sw * .7, PAL.ink, 'inkfine', .3); }
  }

  // the action: pose offsets over time, spread into clawd()
  function act(t) {
    const after = t > SWITCH;
    switch (SC.action) {
      case 'wave': return move('wave', t);
      case 'think': return { ...move('idle', t), aR: .95, lookY: -.6, lookX: .5 };
      case 'idea': return after ? { ...move('hop', t), aL: 1.3, aR: 1.3 } : { ...move('idle', t), lookY: -.4 };
      case 'walk': { const s = stroll(t, .2, DUR * .7, X - 260, X + 120, UNIT); return { ...s, dx: (s.x - X) / UNIT, x: undefined }; }
      case 'work': return { ...move('idle', t), aL: .15 + .25 * Math.sin(t * 22), aR: .15 + .25 * Math.cos(t * 22), lookY: .4 };
      case 'celebrate': return after ? move('roof', t) : move('idle', t);
      case 'shrug': return after ? { aL: 1.05, aR: 1.05, ...take(t, SWITCH, .6) } : move('idle', t);
      case 'sleep': return after ? take(t, SWITCH, 1) : { ...move('idle', t), dy: .3 };
      case 'dance': return move('mix', t);
      case 'scared': return { dx: Math.sin(t * 38) * .25, aL: .9, aR: .9 };
      case 'sad': return { dy: .2, aL: -.4, aR: -.4 };
      case 'proud': return { ...move('idle', t), aL: -.2, aR: -.2, dy: -.3 };
      default: return move('idle', t);
    }
  }

  shots([[0, (t, lt, dur) => {
    const z = kf(t, [[0, 1], [DUR, 1.07]]), sh = t > SWITCH && t < SWITCH + .3 ? shakeXY(t, 4 * Math.exp(-(t - SWITCH) * 9)) : [0, 0];
    camBegin(X + sh[0], H * .58 + sh[1], z);
    backdrop(t);
    const face = emotions(t, [[0, SC.from], [SWITCH, SC.to]]), pose = act(t);
    const o = { ...face, ...pose, dy: (face.dy || 0) + (pose.dy || 0), sq: (face.sq || 0) + (pose.sq || 0) };
    if (SC.hat) o.hat = SC.hat;
    if (SC.prop) { o.armR = prop; if (o.aR == null || o.aR < .4) o.aR = .5; }
    clawd(X, Y, UNIT, o);
    camEnd();
    if (lt < .25) brushWipe(.5 + lt / .5);
  }]]);
})();
`;
}

// Paint one clawd scene into <work>/art/<key>/clip.mp4 (dur = its length now; a longer scene holds the last frame).
async function paint(work, scene, dur, log = () => {}) {
  await ensureStudio(log);
  const key = artKey(scene), dir = path.resolve(work, "art", key), out = path.join(dir, "clip.mp4");
  fs.mkdirSync(dir, { recursive: true });
  const len = Math.max(2.5, Math.min(12, dur + 0.4));
  fs.writeFileSync(path.join(STUDIO, "src", "scenes", "reel.js"), shotJs(scene, len));
  fs.writeFileSync(path.join(STUDIO, "src", "config.js"), `const PROJECT = { duration: ${len.toFixed(2)}, bpm: 120, offset: 0 };\n`);
  const chrome = require("playwright").chromium.executablePath();
  log(`painting Clawd (${scene.action}, ${scene.from} → ${scene.to}, ${len.toFixed(1)} s)… this is slow: a few seconds per frame`);
  let last = 0;
  await U.run(process.execPath, ["render.mjs", "--clip", `--fps=${FPS}`, `--out=${out}`, `--chrome=${chrome}`], { cwd: STUDIO,
    log: l => { const m = l.match(/(\d+)\s*\/\s*(\d+)/); if (!m) return; const pc = Math.floor(100 * m[1] / m[2] / 10) * 10; if (pc > last) { last = pc; log(`  painted ${pc}%`); } } });
  U.writeJson(path.join(dir, "art.json"), { kind: "clawd", fps: FPS, len, made: new Date().toISOString() });
  log(`✓ Clawd scene painted`);
  return out;
}

module.exports = { artKey, ensureStudio, paint, shotJs, STUDIO, FPS };
